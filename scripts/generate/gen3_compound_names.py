"""Generate the Generation III compound-name casing table from PokéDB.

Generation III stores names in capitals, so "THUNDERPUNCH" recases to
"Thunderpunch". PokéDB's slugs mark the word boundaries ("thunder-punch"), so
every move, ability, and item slug of two or more words gives the casing
of its run-together capitals ("THUNDERPUNCH" -> "ThunderPunch"), the
spelling the games of that era used. Only capitalization ever changes: a
ROM word is recased only when its letters match a key exactly. Run from the
repository root:

    python scripts/generate/gen3_compound_names.py [--pokedb-root DIR] [--check]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from common import ROOT, check_or_write, local_config, local_path

OUTPUT = ROOT / "src/romwiki/engines/gen3/shared/compound_names.py"
_KINDS = ("move", "ability", "item")


def _pokedb_root(configured: Path | None) -> Path:
    if configured is not None:
        return configured
    root = local_config().get("pokedb_root")
    if not isinstance(root, str):
        raise SystemExit("Set pokedb_root in .local/games.toml or pass --pokedb-root")
    return local_path(root)


def generate(pokedb_root: Path) -> str:
    generation = pokedb_root / "gen3"
    compounds: dict[str, str] = {}
    for kind in _KINDS:
        for path in sorted((generation / kind).glob("*.json")):
            slug = json.loads(path.read_text(encoding="utf-8"))["name"]
            parts = slug.split("-")
            if len(parts) > 1 and all(part.isalpha() for part in parts):
                compounds.setdefault(
                    "".join(parts).upper(),
                    "".join(part.capitalize() for part in parts),
                )
    if not compounds:
        raise SystemExit(f"No PokéDB move, ability, or item names in {generation}")
    entries = "".join(
        f'    "{key}": "{value}",\n' for key, value in sorted(compounds.items())
    )
    return (
        '"""Casing of run-together Generation III names, by their capitals.\n\n'
        "Generated by scripts/generate/gen3_compound_names.py from PokéDB's\n"
        "Generation III "
        'move, ability, and item slugs. Do not edit by hand.\n"""\n\n'
        "from __future__ import annotations\n\n"
        "COMPOUND_NAMES: dict[str, str] = {\n" + entries + "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pokedb-root", type=Path)
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    args = parser.parse_args()
    check_or_write({OUTPUT: generate(_pokedb_root(args.pokedb_root))}, check=args.check)


if __name__ == "__main__":
    main()
