"""Generate the Black 2/White 2 field-script command table from pokebw2.

`include/asm/field_script.inc` in fuddlesworth/pokebw2 defines one macro per
command: `FieldCommand <opcode>` followed by its operands as `.byte`, `.2byte`,
and `.4byte` directives. The decompilation reassembles every script with these
macros and rebuilds both ROMs byte for byte, so the widths are exact.

Commands from 0x3E8 belong to plugins (overlays a script loads for one feature,
such as the pleasure boat): each plugin numbers its commands from 0x3E8, so one
opcode means different commands in different scripts. The table keeps a plugin
opcode only when every plugin gives it the same width, so disassembly never
reads past one with the wrong width; a script's plugin isn't known statically.
Run from the repository root:

    python scripts/generate/gen5_b2w2_script_commands.py [--check]
"""

from __future__ import annotations

import argparse
import json
import re

from common import ROOT, check_or_write
from decomp_sources import pinned, read

OUTPUT = ROOT / "src/romwiki/engines/gen5/b2w2/script_command_table.py"
_PROJECT = "pokebw2"
_MACROS = "include/asm/field_script.inc"
_SIZES = {".byte": 1, ".2byte": 2, ".4byte": 4}
_FIRST_PLUGIN_OPCODE = 0x3E8


def commands() -> dict[int, tuple[str, tuple[int, ...]]]:
    definitions: dict[int, list[tuple[str, tuple[int, ...]]]] = {}
    text = read(_PROJECT, _MACROS)
    for match in re.finditer(r"\.macro\s+(\w+)[^\n]*\n(.*?)\n\s*\.endm", text, re.S):
        name = match.group(1)
        lines = [
            line.split("//")[0].strip()
            for line in match.group(2).splitlines()
            if line.split("//")[0].strip()
        ]
        if not lines or not lines[0].startswith("FieldCommand "):
            continue
        opcode = int(lines[0].split()[1], 0)
        widths = []
        for line in lines[1:]:
            directive = line.split()[0]
            if directive not in _SIZES:
                raise SystemExit(f"{name}: unexpected operand line {line!r}")
            widths.append(_SIZES[directive])
        definitions.setdefault(opcode, []).append((name, tuple(widths)))
    if not definitions:
        raise SystemExit(f"No field commands found in {_MACROS}")
    table: dict[int, tuple[str, tuple[int, ...]]] = {}
    for opcode, defined in definitions.items():
        if len(defined) == 1:
            table[opcode] = defined[0]
        elif opcode < _FIRST_PLUGIN_OPCODE:
            raise SystemExit(f"Core opcode {opcode:#x} is defined twice: {defined}")
        elif len({widths for _, widths in defined}) == 1:
            table[opcode] = (f"PluginCmd_{opcode:04X}", defined[0][1])
    return table


def generate() -> str:
    repository, commit = pinned(_PROJECT)
    entries = "".join(
        f"    0x{opcode:03X}: ({json.dumps(name)}, {widths!r}),\n"
        for opcode, (name, widths) in sorted(commands().items())
    )
    return (
        '"""Black 2/White 2 field-script commands: opcode -> (name, operand widths).\n\n'
        f"Generated by scripts/generate/gen5_b2w2_script_commands.py from\n"
        f"{repository}@{commit[:12]} ({_MACROS}). Do not edit by hand.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "SCRIPT_COMMANDS: dict[int, tuple[str, tuple[int, ...]]] = {\n"
        + entries
        + "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    args = parser.parse_args()
    check_or_write({OUTPUT: generate()}, check=args.check)


if __name__ == "__main__":
    main()
