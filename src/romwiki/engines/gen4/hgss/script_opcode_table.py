"""HeartGold/SoulSilver field-script opcode table (through opcode 0x354).

Sourced from pret/pokeheartgold's decompilation of the real HeartGold
source (`tools/py_scripts/scrcmd.json`, itself derived from
`asm/fieldmap_s.s`'s `gScriptCmdTable` dispatch-pointer order cross-referenced
against each handler's real `ScriptRead{Byte,Halfword,Word}` calls) -- an
authoritative source, not a guess.

Verified two ways against this codebase's own independently-decoded facts
before this table existed:

1. Every opcode this codebase had already independently verified against
   real ROM bytes matches exactly: 0xD5 TrainerBattle (`gen4/hgss/scripts.py`'s
   `START_TRAINER_BATTLE`), 0xDC CheckBattleWon (`CHECK_WON_BATTLE`), and the
   shared low-numbered VM control-flow opcodes DPPT and HGSS both use
   identically (0x02 End, 0x16 GoTo, 0x1A Call, 0x1B Return, 0x1C GoToIf,
   0x1D CallIf) -- unlike the game-specific "high" opcodes (item/party/mart/
   battle commands), which HGSS renumbers independently of Platinum.
2. Cross-checked TrainerBattle's real operand width against the live
   HeartGold ROM directly: this table (and pret/pokeheartgold) both give
   TrainerBattle four params (trainer, var, 1, 1 -- 6 bytes), not the
   4-byte (trainer, var) width the project's pre-existing byte-scanner
   assumed. Scanning the real ROM's script archive (`a/0/1/2`) confirms
   every literal-trainer TrainerBattle site's bytes at offset+6..+8 are
   `00 00` (the previously-undocumented trailing flag bytes), with the real
   follow-on opcode two bytes further out than the old scanner checked --
   the old scanner's follow-on check was accidentally reading mid-operand
   bytes (always 0x0000 = a trivially "valid" opcode) rather than the real
   next instruction, which happened to not corrupt its extracted trainer
   IDs (those are read at correct, unaffected offsets) but never actually
   validated anything for HGSS. Running this table's disassembler across
   every parseable script file (494 of 965; the rest aren't field scripts)
   found 123 statically-reachable TrainerBattle sites against the existing
   byte-scanner's 121 -- the small delta is fully explained by the two
   techniques' different reach (static control-flow-following vs. an
   unanchored byte scan), not by a table error.

Five commands (of 853) use a variable-width encoding this table does not
represent and are omitted, mirroring Platinum's table's precedent for its
own 6 such commands: 0x190 StrengthFlagAction, 0x191 FlashAction,
0x192 DefogAction, 0x1D1 (unnamed, ScrCmd_465), and 0x1E9 MysteryGift.
Nothing in this codebase currently needs to disassemble past them.
"""

